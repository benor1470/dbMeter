INSERT INTO orders (customer_id, order_date, amount)
SELECT x % 100 + 1, DATE '2026-01-01' + x % 365, (x * 37) % 1000 / 10.0 + 1
FROM generate_series(1, 5000) AS x;

-- Dollar-quoted body: the ';' inside does not split the script.
CREATE FUNCTION customer_total(cid INT) RETURNS NUMERIC
LANGUAGE plpgsql STABLE AS $$
DECLARE
    total NUMERIC;
BEGIN
    SELECT COALESCE(SUM(amount), 0) INTO total FROM orders WHERE customer_id = cid;
    RETURN total;
END;
$$;

