-- Test schema in its own PostgreSQL schema: 100 customers in 4 regions, 5000 orders.
DROP SCHEMA IF EXISTS dbmeter_test CASCADE;
CREATE SCHEMA dbmeter_test;
SET search_path TO dbmeter_test;

CREATE TABLE customers (
    id     INT PRIMARY KEY,
    name   TEXT NOT NULL,
    region TEXT NOT NULL
);

CREATE TABLE orders (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id INT           NOT NULL REFERENCES customers (id),
    order_date  DATE          NOT NULL,
    amount      NUMERIC(12,2) NOT NULL
);
CREATE INDEX orders_customer ON orders (customer_id);

CREATE TABLE audit_log (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    thread_no INT       NOT NULL,
    iteration BIGINT    NOT NULL,
    logged_at TIMESTAMP NOT NULL,
    note      TEXT
);

INSERT INTO customers
