"""Table-size scaling benchmark for PostgreSQL, InMemory.Net IRDB and RAMSQL.

The same four queries (PK lookup, filtered scan, top-N sort, fetch all) - all inside RAMSQL's supported
SQL subset - run against tables of 100 .. 1,000,000 rows, so the results isolate table-size behavior.
Row i of every table t_<N>: id=i, grp=i%10, val=(i*7919) % 1000003 (unique), name='row-<i>'.

Writes: sql/pg_schema.sql, expected/*.csv, pg/irdb/ramsql .properties, and the RAMSQL multi-row
INSERT scripts (batches of BATCH rows) into ../../build/size-scaling/.

Usage: python -I gen.py
"""
import os

SIZES = [100, 512, 1000, 10_000, 100_000, 1_000_000]
HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.normpath(os.path.join(HERE, "..", "..", "build", "size-scaling"))
P = 1_000_003
FILTER_GRP, FILTER_MIN = 3, 990_000
TEXT_BYTES = 200
BATCH = 100


def val(i):
    return (i * 7919) % P


def write(path, lines):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def pg_schema():
    lines = ["-- Generated by gen.py. One table per size; PK index only (as in RAMSQL).",
             "DROP SCHEMA IF EXISTS dbmeter_size CASCADE;",
             "CREATE SCHEMA dbmeter_size;",
             "SET search_path TO dbmeter_size;"]
    for n in SIZES:
        lines += ["CREATE UNLOGGED TABLE t_%d (id INT PRIMARY KEY, grp INT NOT NULL, val INT NOT NULL, name TEXT NOT NULL);" % n,
                  "INSERT INTO t_%d SELECT i, i %% 10, (i::bigint * 7919) %% %d, 'row-' || i FROM generate_series(1, %d) i;"
                  % (n, P, n)]
    lines.append("VACUUM ANALYZE;")
    write(os.path.join(HERE, "sql", "pg_schema.sql"), lines)


def ramsql_loads():
    for n in SIZES:
        lines = ["DROP TABLE t_%d;" % n,
                 "CREATE TABLE t_%d (id INT PRIMARY KEY, grp INT NOT NULL, val INT NOT NULL, name TEXT NOT NULL);" % n]
        # Multi-row VALUES, BATCH rows per statement: RAMSQL allows 512 expression nodes (~110 rows of 4 values)
        # and 16 KB per query packet.
        for lo in range(1, n + 1, BATCH):
            rows = ", ".join("(%d, %d, %d, 'row-%d')" % (i, i % 10, val(i), i) for i in range(lo, min(lo + BATCH, n + 1)))
            lines.append("INSERT INTO t_%d (id, grp, val, name) VALUES %s;" % (n, rows))
        write(os.path.join(BUILD, "ramsql_load_t_%d.sql" % n), lines)


def expected():
    for n in SIZES:
        write(os.path.join(HERE, "expected", "s%d_pk.csv" % n),
              ["id,grp,val,name", "%d,%d,%d,row-%d" % (n, n % 10, val(n), n)])
        hits = [i for i in range(1, n + 1) if i % 10 == FILTER_GRP and val(i) > FILTER_MIN]
        write(os.path.join(HERE, "expected", "s%d_filter.csv" % n), ["id,val"] + ["%d,%d" % (i, val(i)) for i in hits])
        top = sorted(range(1, n + 1), key=lambda i: -val(i))[:10]
        write(os.path.join(HERE, "expected", "s%d_topn.csv" % n), ["id,val"] + ["%d,%d" % (i, val(i)) for i in top])


def size_section(n):
    t = "t_%d" % n
    s = "s%d" % n
    return [
        "# ---- %s rows ----" % format(n, ","),
        "check.%s_a_pk.sql=SELECT id, grp, val, name FROM %s WHERE id = %d" % (s, t, n),
        "check.%s_a_pk.expect.csv=expected/%s_pk.csv" % (s, s),
        "check.%s_b_filter.sql=SELECT id, val FROM %s WHERE grp = %d AND val > %d ORDER BY id" % (s, t, FILTER_GRP, FILTER_MIN),
        "check.%s_b_filter.expect.csv=expected/%s_filter.csv" % (s, s),
        "check.%s_b_filter.expect.ordered=true" % s,
        "check.%s_c_topn.sql=SELECT id, val FROM %s ORDER BY val DESC LIMIT 10" % (s, t),
        "check.%s_c_topn.expect.csv=expected/%s_topn.csv" % (s, s),
        "check.%s_c_topn.expect.ordered=true" % s,
        "check.%s_d_last.sql=SELECT id FROM %s ORDER BY id DESC LIMIT 1" % (s, t),
        "check.%s_d_last.expect.value=%d" % (s, n),
        "scenario.%s_pk.sql=SELECT id, grp, val, name FROM %s WHERE id = :{$rand(1,%d):int}" % (s, t, n),
        "scenario.%s_filter.sql=SELECT id, val FROM %s WHERE grp = :{$rand(0,9):int} AND val > %d" % (s, t, FILTER_MIN),
        "scenario.%s_topn.sql=SELECT id, val FROM %s ORDER BY val DESC LIMIT 10" % (s, t),
        "scenario.%s_fetch_all.sql=SELECT id, grp, val, name FROM %s" % (s, t),
        "",
    ]


CAPACITY = [
    "# ---- capacity probes (PostgreSQL behavior expected) ----",
    "check.cap_a_text_%d_bytes.sql=CREATE TABLE cap_text (id INT PRIMARY KEY, t TEXT NOT NULL); "
    "INSERT INTO cap_text (id, t) VALUES (1, '%s'); SELECT t FROM cap_text WHERE id = 1" % (TEXT_BYTES, "x" * TEXT_BYTES),
    "check.cap_a_text_%d_bytes.expect.value=%s" % (TEXT_BYTES, "x" * TEXT_BYTES),
    "check.cap_b_9_columns.sql=CREATE TABLE cap_cols (c1 INT PRIMARY KEY, c2 INT, c3 INT, c4 INT, c5 INT, c6 INT, c7 INT, "
    "c8 INT, c9 INT); INSERT INTO cap_cols (c1, c2, c3, c4, c5, c6, c7, c8, c9) VALUES (1, 2, 3, 4, 5, 6, 7, 8, 9); "
    "SELECT c9 FROM cap_cols WHERE c1 = 1",
    "check.cap_b_9_columns.expect.value=9",
    "check.cap_c_20_more_tables.sql=" + " ".join("CREATE TABLE cap_tbl_%02d (id INT PRIMARY KEY);" % k for k in range(1, 21))
    + " SELECT id FROM cap_tbl_20",
    "check.cap_c_20_more_tables.expect.rows=0",
    "",
]

COMMON_LOAD = [
    "# ---- load: run one size at a time with --only s<N>_pk,s<N>_filter,s<N>_topn,s<N>_fetch_all ----",
    "load.threads=8",
    "load.warmup=3s",
    "load.duration=10s",
    "load.reportInterval=5s",
    "load.queryTimeout=120s",
    "",
]

HEADERS = {
    "pg": [
        "# Generated by gen.py - table-size scaling benchmark on PostgreSQL.",
        "driver.jar=../../drivers/postgresql-42.7.4.jar",
        "jdbc.url=jdbc:postgresql://${env:PGHOST:-localhost}:${env:PGPORT:-5432}/${env:PGDATABASE:-postgres}",
        "jdbc.user=${env:PGUSER:-postgres}",
        "jdbc.password=${env:PGPASSWORD:-1}",
        "connection.init.sql=SET search_path TO dbmeter_size",
        "check.setup.file=sql/pg_schema.sql",
        "",
    ],
    "irdb": [
        "# Generated by gen.py - table-size scaling benchmark on InMemory.Net IRDB (data copied from PostgreSQL).",
        "driver.jar=../../build/irdb-jdbc.jar, ../../drivers/jirdb-2025-02-02.jar, ../../drivers/fastutil-8.5.15.jar",
        "jdbc.url=jdbc:irdb://${env:IRDB_HOST:-localhost}:${env:IRDB_PORT:-5060}/size_bench",
        "jdbc.user=${env:IRDB_USER:-default}",
        "jdbc.password=${env:IRDB_PASSWORD:-!TopSecret}",
        "",
    ],
    "ramsql": [
        "# Generated by gen.py - table-size scaling benchmark on RAMSQL (fresh server: ramsql --memory --insecure-local --port 5433 --rows 1000000).",
        "# Tables are loaded per size by run_all.ps1 with ../../build/size-scaling/ramsql_load_t_<N>.sql.",
        "driver.jar=../../drivers/postgresql-42.7.4.jar",
        "jdbc.url=jdbc:postgresql://127.0.0.1:${env:RAMSQL_PORT:-5433}/ramsql",
        "jdbc.user=postgres",
        "jdbc.password=",
        "jdbc.prop.sslmode=disable",
        "run.databaseLabel=RAMSQL 0.3.0-beta.1",
        "",
    ],
}


def configs():
    for db, header in HEADERS.items():
        lines = list(header)
        for n in SIZES:
            lines += size_section(n)
        if db != "irdb":
            lines += CAPACITY
        lines += COMMON_LOAD
        write(os.path.join(HERE, "%s.properties" % db), lines)


if __name__ == "__main__":
    pg_schema()
    expected()
    configs()
    ramsql_loads()
    print("generated sizes", SIZES, "->", HERE, "and", BUILD)
