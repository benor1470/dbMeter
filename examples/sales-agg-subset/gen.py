"""Sales aggregation workload in the SQL subset shared by PostgreSQL and RAMSQL (>= 0.3.0-beta.1).

Same star schema and integer formulas as ../sales-agg (keep them in sync), but 1,000,000 sales rows
(RAMSQL's --rows budget commits ~19 KB per row slot, so 5M rows don't fit in RAM) and queries rewritten
without what RAMSQL lacks: to_char, window functions, ROLLUP and ROUND. Results are recomputed in Python,
independently of both databases.

Writes: sql/pg_schema.sql, expected/*.csv and ../../build/sales-agg-subset/ramsql_load.sql
(multi-row INSERTs of BATCH rows: RAMSQL allows 512 expression nodes per statement, ~60 rows of 8 values).

Usage: python -I gen.py [rows]      (default 1000000)
"""
import os
import sys
from datetime import date, timedelta

N = int(sys.argv[1]) if len(sys.argv) > 1 else 1_000_000
HERE = os.path.dirname(os.path.abspath(__file__))
BUILD = os.path.normpath(os.path.join(HERE, "..", "..", "build", "sales-agg-subset"))
BATCH = 50

REGIONS = {1: "North", 2: "South", 3: "East", 4: "West", 5: "Central"}
SEGMENTS = ["Consumer", "Corporate", "Home Office", "Small Business"]
P = 2147483647  # prime modulus of the per-column hashes
HIGH_VALUE_CENTS = 380_000  # ~ the mean customer total at 1M rows (../sales-agg uses 1,900,000 at 5M)
Q6_STORE = 17
Q6_FROM, Q6_TO = 59, 242  # 2025-03-01 .. 2025-08-31 as days after 2025-01-01

store_region = [None] + [REGIONS[s % 5 + 1] for s in range(1, 201)]
cat_name = [None] + ["Category %02d" % c for c in range(1, 21)]
price = [0] + [100 + (p * 7919) % 10000 for p in range(1, 1001)]
product_cat = [0] + [p % 20 + 1 for p in range(1, 1001)]
segment = [None] + [SEGMENTS[c % 4] for c in range(1, 50001)]
DAYS = [(date(2025, 1, 1) + timedelta(days=d)).isoformat() for d in range(730)]


def write(path, lines):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def csv(name, header, rows):
    write(os.path.join(HERE, "expected", name), [",".join(header)] + [",".join(str(v) for v in r) for r in rows])


def sale(i):
    pid = (i * 1103515245) % P % 1000 + 1
    sid = (i * 950706376) % P % 200 + 1
    cid = (i * 742938285) % P % 50000 + 1
    day = (i * 1583458089) % P % 730
    qty = (i * 1226874159) % P % 7 + 1
    disc = (i * 630360016) % P % 4 * 5
    return pid, sid, cid, day, qty, disc, qty * price[pid] * (100 - disc) // 100


def pg_schema():
    write(os.path.join(HERE, "sql", "pg_schema.sql"), [
        "-- Generated by gen.py: ../sales-agg/sql/schema.sql with %d sales rows in schema dbmeter_agg_subset." % N,
        "DROP SCHEMA IF EXISTS dbmeter_agg_subset CASCADE;",
        "CREATE SCHEMA dbmeter_agg_subset;",
        "SET search_path TO dbmeter_agg_subset;",
        "CREATE UNLOGGED TABLE regions (id INT PRIMARY KEY, name TEXT NOT NULL);",
        "INSERT INTO regions VALUES (1, 'North'), (2, 'South'), (3, 'East'), (4, 'West'), (5, 'Central');",
        "CREATE UNLOGGED TABLE stores (id INT PRIMARY KEY, region_id INT NOT NULL, name TEXT NOT NULL);",
        "INSERT INTO stores SELECT s, s % 5 + 1, 'Store ' || s FROM generate_series(1, 200) s;",
        "CREATE UNLOGGED TABLE categories (id INT PRIMARY KEY, name TEXT NOT NULL);",
        "INSERT INTO categories SELECT c, 'Category ' || lpad(c::text, 2, '0') FROM generate_series(1, 20) c;",
        "CREATE UNLOGGED TABLE products (id INT PRIMARY KEY, category_id INT NOT NULL, unit_price_cents INT NOT NULL);",
        "INSERT INTO products SELECT p, p % 20 + 1, 100 + (p * 7919) % 10000 FROM generate_series(1, 1000) p;",
        "CREATE UNLOGGED TABLE customers (id INT PRIMARY KEY, segment TEXT NOT NULL);",
        "INSERT INTO customers SELECT c, (ARRAY['Consumer', 'Corporate', 'Home Office', 'Small Business'])[c % 4 + 1]"
        " FROM generate_series(1, 50000) c;",
        "CREATE UNLOGGED TABLE sales (id BIGINT PRIMARY KEY, product_id INT NOT NULL, store_id INT NOT NULL,"
        " customer_id INT NOT NULL, sale_date DATE NOT NULL, quantity INT NOT NULL, discount_pct INT NOT NULL,"
        " amount_cents BIGINT NOT NULL);",
        "INSERT INTO sales SELECT g.i, g.pid, g.sid, g.cid, DATE '2025-01-01' + g.day::int, g.qty, g.disc,"
        " g.qty * p.unit_price_cents * (100 - g.disc) / 100 FROM ("
        " SELECT i, (i * 1103515245) % 2147483647 % 1000 + 1 AS pid, (i * 950706376) % 2147483647 % 200 + 1 AS sid,"
        " (i * 742938285) % 2147483647 % 50000 + 1 AS cid, (i * 1583458089) % 2147483647 % 730 AS day,"
        " (i * 1226874159) % 2147483647 % 7 + 1 AS qty, (i * 630360016) % 2147483647 % 4 * 5 AS disc"
        " FROM generate_series(1::bigint, {rows}) i) g JOIN products p ON p.id = g.pid;".replace("{rows}", str(N)),
        "VACUUM ANALYZE;",
    ])


def inserts(lines, target, rows):
    for lo in range(0, len(rows), BATCH):
        lines.append("INSERT INTO %s VALUES %s;" % (target, ", ".join(rows[lo:lo + BATCH])))


def ramsql_load():
    lines = ["DROP TABLE %s;" % t for t in ("sales", "customers", "products", "categories", "stores", "regions")]
    lines += [
        "CREATE TABLE regions (id INT PRIMARY KEY, name TEXT NOT NULL);",
        "CREATE TABLE stores (id INT PRIMARY KEY, region_id INT NOT NULL, name TEXT NOT NULL);",
        "CREATE TABLE categories (id INT PRIMARY KEY, name TEXT NOT NULL);",
        "CREATE TABLE products (id INT PRIMARY KEY, category_id INT NOT NULL, unit_price_cents INT NOT NULL);",
        "CREATE TABLE customers (id INT PRIMARY KEY, segment TEXT NOT NULL);",
        "CREATE TABLE sales (id BIGINT PRIMARY KEY, product_id INT NOT NULL, store_id INT NOT NULL,"
        " customer_id INT NOT NULL, sale_date DATE NOT NULL, quantity INT NOT NULL, discount_pct INT NOT NULL,"
        " amount_cents BIGINT NOT NULL);",
    ]
    inserts(lines, "regions (id, name)", ["(%d, '%s')" % kv for kv in REGIONS.items()])
    inserts(lines, "stores (id, region_id, name)", ["(%d, %d, 'Store %d')" % (s, s % 5 + 1, s) for s in range(1, 201)])
    inserts(lines, "categories (id, name)", ["(%d, '%s')" % (c, cat_name[c]) for c in range(1, 21)])
    inserts(lines, "products (id, category_id, unit_price_cents)",
            ["(%d, %d, %d)" % (p, product_cat[p], price[p]) for p in range(1, 1001)])
    inserts(lines, "customers (id, segment)", ["(%d, '%s')" % (c, segment[c]) for c in range(1, 50001)])
    rows = []
    for i in range(1, N + 1):
        pid, sid, cid, day, qty, disc, amt = sale(i)
        rows.append("(%d, %d, %d, %d, DATE '%s', %d, %d, %d)" % (i, pid, sid, cid, DAYS[day], qty, disc, amt))
    inserts(lines, "sales (id, product_id, store_id, customer_id, sale_date, quantity, discount_pct, amount_cents)", rows)
    write(os.path.join(BUILD, "ramsql_load.sql"), lines)


def expected():
    total = 0
    reg = {}
    cat_count, cat_rev, cat_cust = [0] * 21, [0] * 21, [set() for _ in range(21)]
    prod_units, prod_rev = [0] * 1001, [0] * 1001
    seg_disc = {}
    cust_count, cust_rev = [0] * 50001, [0] * 50001
    q6 = {}
    for i in range(1, N + 1):
        pid, sid, cid, day, qty, disc, amt = sale(i)
        total += amt
        r = reg.setdefault(store_region[sid], [0, 0, 0])
        r[0] += 1; r[1] += qty; r[2] += amt
        cat = product_cat[pid]
        cat_count[cat] += 1; cat_rev[cat] += amt; cat_cust[cat].add(cid)
        prod_units[pid] += qty; prod_rev[pid] += amt
        b = seg_disc.setdefault((segment[cid], disc), [0, 0])
        b[0] += 1; b[1] += amt
        cust_count[cid] += 1; cust_rev[cid] += amt
        if sid == Q6_STORE and Q6_FROM <= day <= Q6_TO:
            c = q6.setdefault(cat, [0, 0, 0])
            c[0] += 1; c[1] += qty; c[2] += amt

    csv("totals.csv", ["row_count", "revenue_cents"], [[N, total]])
    csv("s1_region.csv", ["region", "sales", "units", "revenue_cents"], [[k] + v for k, v in sorted(reg.items())])
    csv("s2_category.csv", ["category", "sales", "customers", "revenue_cents"],
        [[cat_name[c], cat_count[c], len(cat_cust[c]), cat_rev[c]] for c in range(1, 21)])
    top = sorted(range(1, 1001), key=lambda p: (-prod_rev[p], p))[:10]
    csv("s3_top_products.csv", ["product_id", "units", "revenue_cents"], [[p, prod_units[p], prod_rev[p]] for p in top])
    csv("s4_segment_discount.csv", ["segment", "discount_pct", "sales", "revenue_cents"],
        [[k[0], k[1]] + v for k, v in sorted(seg_disc.items())])
    per_seg = {}
    for c in range(1, 50001):
        if cust_rev[c] > HIGH_VALUE_CENTS:
            s = per_seg.setdefault(segment[c], [0, 0, 0])
            s[0] += 1; s[1] += cust_count[c]; s[2] = max(s[2], cust_rev[c])
    csv("s5_high_value_customers.csv", ["segment", "customers", "sales", "max_total_cents"],
        [[k] + v for k, v in sorted(per_seg.items())])
    csv("s6_store_category_mix.csv", ["category", "sales", "units", "revenue_cents"],
        [[cat_name[c]] + q6[c] for c in sorted(q6)])


if __name__ == "__main__":
    pg_schema()
    ramsql_load()
    expected()
    print("generated %d sales rows -> %s and %s" % (N, HERE, BUILD))
